    # {
    #   "grades": [
    #     {"student": 20260001, "course": 1, "gradeName": "exam", "mark": "14.50",
    #      "coefficient": 2.0},
    #     {"student": 20260002, "course": 1, "gradeName": "quiz", "mark": "12.00"}
    #   ]
