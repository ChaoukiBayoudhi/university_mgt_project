"""
Custom ViewSet actions for student_app (Django 6.1 + DRF).

Difficulty legend
-----------------
EASY     : simple list/detail helpers (count, filter, display)
MEDIUM   : query params, related objects, status updates
ADVANCED : aggregations, enroll flow, transcript / bulk ops

Base prefix (see project urls): /api/
Routers auto-wire every @action below — paths are also listed in urls.py.

Tip for students
----------------
- request.query_params  → GET ?key=value
- request.data          → POST/PUT/PATCH JSON body

Comment rule in this file
-------------------------
Each concept is explained once, at its first appearance.
Later uses stay uncommented unless a new detail is needed.

@action(...) parameters (explained once on the first actions below)
------------------------------------------------------------------
detail=False/True
    False → collection route: /api/<resource>/<url_path>/
    True  → detail route:     /api/<resource>/<pk>/<url_path>/

methods=["get"] / ["post"] / ...
    HTTP verbs accepted for this custom endpoint.

url_path="..."
    Last URL segment generated by the router.

url_name="..."
    "reverse" = from a route NAME, rebuild the URL PATH
    (forward resolve = path → view; reverse = name → path).
    Example: reverse("student-count") → "/api/students/count/"
    Full name = "{basename}-{url_name}" (basename comes from router.register).
"""

from decimal import ROUND_HALF_UP, Decimal

from django.db.models import Avg, Count, Q, Sum
from rest_framework import status, viewsets
from rest_framework.decorators import action
from rest_framework.response import Response

from .enumerations import AcademicLevel, CourseType, InscriptionStatus
from .models import Course, Grade, Inscription, Profile, Student, Teacher
from .serializers import (
    CourseSerializer,
    GradeSerializer,
    InscriptionSerializer,
    ProfileSerializer,
    StudentSerializer,
    TeacherSerializer,
)


class StudentViewSet(viewsets.ModelViewSet):
    queryset = Student.objects.all()
    serializer_class = StudentSerializer

    # ------------------------------------------------------------------
    # EASY
    # ------------------------------------------------------------------

    # What it does: counts students (optionally only active ones).
    # Path: GET /api/students/count/
    # Optional query: ?active=1
    @action(
        detail=False,  # False = collection route /api/<resource>/<url_path>/ (no pk)
        methods=["get"],  # Allowed HTTP method(s) for this action
        url_path="count",  # URL segment → .../count/
        # url_name + reverse (explained once here):
        # reverse("student-count") → "/api/students/count/"
        # basename "student" comes from router.register(..., basename="student")
        url_name="count",
    )
    def count_students(self, request):
        """Return how many students exist (optionally only active)."""
        # query_params.get → None if missing (safer for optional params)
        only_active = request.query_params.get("active") == "1"
        # or (KeyError if missing):
        # only_active = request.query_params["active"] == "1"

        # get_queryset() respects ViewSet hooks/filters
        qs = self.get_queryset()
        # or (skips those hooks):
        # qs = Student.objects.all()

        if only_active:
            qs = qs.filter(isActive=True)
            # or:
            # qs = qs.exclude(isActive=False)

        # .count() → SELECT COUNT(*) (efficient)
        return Response({"count": qs.count()})
        # or (loads all rows — avoid on big tables):
        # return Response({"count": len(list(qs))})

    # What it does: returns familyName + name for one student.
    # Path: GET /api/students/{inscriptionNumber}/full-name/
    @action(
        detail=True,  # True = detail route with <pk>; use self.get_object()
        methods=["get"],
        url_path="full-name",
        url_name="full-name",
    )
    def full_name(self, request, pk=None):
        """Return a simple display name for one student."""
        # get_object() loads the row for URL pk (404 if missing)
        student = self.get_object()
        # or:
        # student = Student.objects.get(pk=pk)
        # or:
        # student = Student.objects.filter(pk=pk).first()  # None if missing

        return Response(
            {
                "inscriptionNumber": student.inscriptionNumber,
                "fullName": f"{student.familyName} {student.name}",
            }
        )
        # or (full serializer payload):
        # return Response(self.get_serializer(student).data)

    # ------------------------------------------------------------------
    # MEDIUM
    # ------------------------------------------------------------------

    # What it does: lists students for a given academic level.
    # Path: GET /api/students/by-level/?level=L1
    @action(
        detail=False,
        methods=["get"],
        url_path="by-level",
        url_name="by-level",
    )
    def by_level(self, request):
        """Filter students by academic level (L1, L2, L3, M1, M2)."""
        # Required query param → validate then 400 if missing
        level = request.query_params.get("level")
        if not level:
            return Response(
                {"detail": "Query param 'level' is required (e.g. L1)."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        # Validate against TextChoices values (not labels)
        valid = {choice.value for choice in AcademicLevel}
        # or:
        # valid = dict(AcademicLevel.choices).keys()
        if level not in valid:
            return Response(
                {"detail": f"Invalid level. Choose one of: {sorted(valid)}"},
                status=status.HTTP_400_BAD_REQUEST,
            )
        qs = self.get_queryset().filter(level=level)
        serializer = self.get_serializer(qs, many=True)
        # or:
        # serializer = StudentSerializer(qs, many=True)
        return Response(serializer.data)

    # What it does: soft-disable a student (isActive=False, no hard delete).
    # Path: POST /api/students/{inscriptionNumber}/deactivate/
    @action(
        detail=True,
        methods=["post"],  # POST = changes server state (not a safe GET)
        url_path="deactivate",
        url_name="deactivate",
    )
    def deactivate(self, request, pk=None):
        """Soft-disable a student (sets isActive=False)."""
        student = self.get_object()
        if not student.isActive:
            return Response(
                {"detail": "Student is already inactive."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        student.isActive = False
        # update_fields = write only these columns
        student.save(update_fields=["isActive", "updatedAt"])
        # or (writes every field):
        # student.save()

        return Response(
            {
                "inscriptionNumber": student.inscriptionNumber,
                "isActive": student.isActive,
            }
        )
        # or (no JSON body):
        # return Response(status=status.HTTP_204_NO_CONTENT)

    # ------------------------------------------------------------------
    # ADVANCED
    # ------------------------------------------------------------------

    # What it does: mini transcript — grades grouped by course + weighted avg /20.
    # Path: GET /api/students/{inscriptionNumber}/transcript/
    # Formula: sum(mark * coefficient) / sum(coefficient)
    @action(
        detail=True,
        methods=["get"],
        url_path="transcript",
        url_name="transcript",
    )
    def transcript(self, request, pk=None):
        """Build a mini transcript: grades + weighted average per course."""
        student = self.get_object()
        # select_related avoids N+1 queries on grade.course
        grades = (
            student.grades.select_related("course")
            .all()
            .order_by("course__code", "gradeName")
        )
        # or (may cause N+1 queries):
        # grades = student.grades.all().order_by("course__code", "gradeName")
        # or:
        # grades = Grade.objects.filter(student=student).select_related("course")

        by_course = {}
        for grade in grades:
            bucket = by_course.setdefault(
                grade.course_id,
                {
                    "courseCode": grade.course.code,
                    "courseTitle": grade.course.title,
                    "items": [],
                    "_weighted": Decimal(0),
                    "_coeff": Decimal(0),
                },
            )
            # Decimal(str(...)) avoids float binary rounding
            coeff = Decimal(str(grade.coefficient))
            mark = Decimal(str(grade.mark))
            bucket["items"].append(
                {
                    "gradeName": grade.gradeName,
                    "mark": str(grade.mark),
                    "maxMark": str(grade.maxMark),
                    "coefficient": grade.coefficient,
                }
            )
            bucket["_weighted"] += mark * coeff
            bucket["_coeff"] += coeff

        courses = []
        for data in by_course.values():
            coeff_sum = data.pop("_coeff")
            weighted = data.pop("_weighted")
            average = None
            if coeff_sum > 0:
                average = (weighted / coeff_sum).quantize(
                    Decimal("0.01"), rounding=ROUND_HALF_UP
                )
            data["weightedAverage"] = str(average) if average is not None else None
            courses.append(data)

        return Response(
            {
                "student": StudentSerializer(student).data,
                "courses": courses,
                "gradeCount": grades.count(),
            }
        )


class TeacherViewSet(viewsets.ModelViewSet):
    queryset = Teacher.objects.all()
    serializer_class = TeacherSerializer
    # permission_classes = [IsAuthenticated]
    # authentication_classes = [TokenAuthentication]

    # ------------------------------------------------------------------
    # EASY
    # ------------------------------------------------------------------

    # What it does: lists active teachers only.
    # Path: GET /api/teachers/active/
    @action(detail=False, methods=["get"], url_path="active", url_name="active")
    def active_teachers(self, request):
        """List teachers with isActive=True."""
        qs = self.get_queryset().filter(isActive=True)
        serializer = self.get_serializer(qs, many=True)
        return Response(serializer.data)

    # ------------------------------------------------------------------
    # MEDIUM
    # ------------------------------------------------------------------

    # What it does: lists courses taught by this teacher (related_name='courses').
    # Path: GET /api/teachers/{id}/courses/
    @action(detail=True, methods=["get"], url_path="courses", url_name="courses")
    def teacher_courses(self, request, pk=None):
        """List courses assigned to this teacher."""
        teacher = self.get_object()
        # Reverse FK: teacher.courses.all()
        courses = teacher.courses.all()
        return Response(CourseSerializer(courses, many=True).data)

    # ------------------------------------------------------------------
    # ADVANCED
    # ------------------------------------------------------------------

    # What it does: teaching load aggregates (courses, credits, capacity).
    # Path: GET /api/teachers/{id}/workload/
    @action(detail=True, methods=["get"], url_path="workload", url_name="workload")
    def workload(self, request, pk=None):
        """Aggregate teaching load: course count, credits, max students."""
        teacher = self.get_object()
        # aggregate() computes in SQL and returns one dict
        stats = teacher.courses.filter(isActive=True).aggregate(
            courseCount=Count("id"),
            totalCredits=Sum("credits"),
            totalCapacity=Sum("maxStudents"),
        )
        # or (Python-side — slower on large data):
        # courses = list(teacher.courses.filter(isActive=True))
        # stats = {
        #     "courseCount": len(courses),
        #     "totalCredits": sum(c.credits for c in courses),
        #     "totalCapacity": sum(c.maxStudents for c in courses),
        # }
        return Response(
            {
                "teacherId": teacher.pk,
                "teacherName": str(teacher),
                "courseCount": stats["courseCount"] or 0,
                "totalCredits": stats["totalCredits"] or 0,
                "totalCapacity": stats["totalCapacity"] or 0,
            }
        )


class CourseViewSet(viewsets.ModelViewSet):
    queryset = Course.objects.all()
    serializer_class = CourseSerializer

    # ------------------------------------------------------------------
    # EASY
    # ------------------------------------------------------------------

    # What it does: filters courses by delivery type.
    # Path: GET /api/courses/by-type/?type=online
    @action(detail=False, methods=["get"], url_path="by-type", url_name="by-type")
    def by_type(self, request):
        """Filter courses by CourseType (online / onsite / hybrid)."""
        course_type = request.query_params.get("type")
        if not course_type:
            return Response(
                {"detail": "Query param 'type' is required."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        valid = {choice.value for choice in CourseType}
        if course_type not in valid:
            return Response(
                {"detail": f"Invalid type. Choose one of: {sorted(valid)}"},
                status=status.HTTP_400_BAD_REQUEST,
            )
        qs = self.get_queryset().filter(type=course_type)
        return Response(self.get_serializer(qs, many=True).data)

    # ------------------------------------------------------------------
    # MEDIUM
    # ------------------------------------------------------------------

    # What it does: students inscribed in one course (any situation).
    # Path: GET /api/courses/{id}/enrolled-students/
    @action(
        detail=True,
        methods=["get"],
        url_path="enrolled-students",
        url_name="enrolled-students",
    )
    def enrolled_students(self, request, pk=None):
        """Students inscribed in this course (any situation)."""
        course = self.get_object()
        # values_list(..., flat=True) → plain list of PKs
        student_ids = course.inscriptions.values_list("student_id", flat=True)
        # or (1-tuples if flat=True is omitted):
        # student_ids = course.inscriptions.values_list("student_id")

        students = Student.objects.filter(pk__in=student_ids)
        # or (single join query):
        # students = Student.objects.filter(inscriptions__course=course).distinct()
        return Response(StudentSerializer(students, many=True).data)

    # ------------------------------------------------------------------
    # ADVANCED
    # ------------------------------------------------------------------

    # What it does: enroll a student (creates PENDING inscription).
    # Path: POST /api/courses/{id}/enroll/
    # Body JSON: {"inscriptionNumber": 12345}
    @action(detail=True, methods=["post"], url_path="enroll", url_name="enroll")
    def enroll(self, request, pk=None):
        """Enroll a student; reject if full or already inscribed."""
        course = self.get_object()

        # request.data = JSON body (POST/PUT/PATCH)
        inscription_number = request.data.get("inscriptionNumber")
        # or:
        # inscription_number = request.data["inscriptionNumber"]

        if inscription_number is None:
            return Response(
                {"detail": "Field 'inscriptionNumber' is required."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        try:
            student = Student.objects.get(pk=inscription_number)
        except Student.DoesNotExist:
            # or:
            # student = Student.objects.filter(pk=inscription_number).first()
            # if student is None: return Response(..., status=404)
            return Response(
                {"detail": "Student not found."},
                status=status.HTTP_404_NOT_FOUND,
            )

        if not course.isActive:
            return Response(
                {"detail": "Course is not active."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        current = course.inscriptions.exclude(
            situation=InscriptionStatus.CANCELLED
        ).count()
        if current >= course.maxStudents:
            # 409 = understood, but conflicts with current state
            return Response(
                {"detail": "Course is full."},
                status=status.HTTP_409_CONFLICT,
            )

        if Inscription.objects.filter(student=student, course=course).exists():
            # or:
            # if Inscription.objects.filter(...).count() > 0:
            return Response(
                {"detail": "Student is already inscribed in this course."},
                status=status.HTTP_409_CONFLICT,
            )

        inscription = Inscription.objects.create(
            student=student,
            course=course,
            situation=InscriptionStatus.PENDING,
        )
        return Response(
            InscriptionSerializer(inscription).data,
            status=status.HTTP_201_CREATED,
        )

    # What it does: enrollment counters + grade average for one course.
    # Path: GET /api/courses/{id}/stats/
    @action(detail=True, methods=["get"], url_path="stats", url_name="stats")
    def stats(self, request, pk=None):
        """Enrollment + grade aggregates for one course."""
        course = self.get_object()
        # Conditional Count(filter=Q(...)) = several totals in one SQL query
        enrollment = course.inscriptions.aggregate(
            total=Count("student"),
            accepted=Count("student", filter=Q(situation=InscriptionStatus.ACCEPTED)),
            pending=Count("student", filter=Q(situation=InscriptionStatus.PENDING)),
        )
        grade_stats = course.grades.aggregate(
            gradeCount=Count("mark"),
            averageMark=Avg("mark"),
        )
        avg = grade_stats["averageMark"]
        return Response(
            {
                "course": CourseSerializer(course).data,
                "enrollment": enrollment,
                "seatsLeft": max(course.maxStudents - (enrollment["total"] or 0), 0),
                "grades": {
                    "gradeCount": grade_stats["gradeCount"] or 0,
                    "averageMark": (
                        str(
                            Decimal(str(avg)).quantize(
                                Decimal("0.01"), rounding=ROUND_HALF_UP
                            )
                        )
                        if avg is not None
                        else None
                    ),
                },
            }
        )


class GradeViewSet(viewsets.ModelViewSet):
    queryset = Grade.objects.all()
    serializer_class = GradeSerializer

    # ------------------------------------------------------------------
    # EASY
    # ------------------------------------------------------------------

    # What it does: grades with mark >= 16 / 20.
    # Path: GET /api/grades/high-scores/
    @action(
        detail=False,
        methods=["get"],
        url_path="high-scores",
        url_name="high-scores",
    )
    def high_scores(self, request):
        """Grades with mark >= 16 / 20."""
        qs = (
            self.get_queryset().filter(mark__gte=16).select_related("student", "course")
        )
        return Response(self.get_serializer(qs, many=True).data)

    # ------------------------------------------------------------------
    # MEDIUM
    # ------------------------------------------------------------------

    # What it does: all grades for one course.
    # Path: GET /api/grades/by-course/?course_id=1
    @action(
        detail=False,
        methods=["get"],
        url_path="by-course",
        url_name="by-course",
    )
    def by_course(self, request):
        """All grades for a given course id."""
        course_id = request.query_params.get("course_id")
        if not course_id:
            return Response(
                {"detail": "Query param 'course_id' is required."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        qs = self.get_queryset().filter(course_id=course_id)
        return Response(self.get_serializer(qs, many=True).data)

    # ------------------------------------------------------------------
    # ADVANCED
    # ------------------------------------------------------------------

    # What it does: per-student weighted average inside one course.
    # Path: GET /api/grades/course-average/?course_id=1
    @action(
        detail=False,
        methods=["get"],
        url_path="course-average",
        url_name="course-average",
    )
    def course_average(self, request):
        """Per-student weighted average: sum(mark*coeff)/sum(coeff)."""
        course_id = request.query_params.get("course_id")
        if not course_id:
            return Response(
                {"detail": "Query param 'course_id' is required."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        if not Course.objects.filter(pk=course_id).exists():
            return Response(
                {"detail": "Course not found."},
                status=status.HTTP_404_NOT_FOUND,
            )

        grades = Grade.objects.filter(course_id=course_id).select_related("student")
        totals = {}
        for grade in grades:
            key = grade.student_id
            entry = totals.setdefault(
                key,
                {
                    "inscriptionNumber": grade.student_id,
                    "studentName": str(grade.student),
                    "_w": Decimal(0),
                    "_c": Decimal(0),
                },
            )
            entry["_w"] += Decimal(str(grade.mark)) * Decimal(str(grade.coefficient))
            entry["_c"] += Decimal(str(grade.coefficient))

        results = []
        for entry in totals.values():
            c = entry.pop("_c")
            w = entry.pop("_w")
            entry["weightedAverage"] = (
                str((w / c).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))
                if c > 0
                else None
            )
            results.append(entry)

        return Response({"courseId": int(course_id), "students": results})


class ProfileViewSet(viewsets.ModelViewSet):
    queryset = Profile.objects.all()
    serializer_class = ProfileSerializer

    # ------------------------------------------------------------------
    # EASY
    # ------------------------------------------------------------------

    # What it does: profiles that have a GitHub URL.
    # Path: GET /api/profiles/with-github/
    @action(
        detail=False,
        methods=["get"],
        url_path="with-github",
        url_name="with-github",
    )
    def with_github(self, request):
        """Profiles that published a GitHub URL."""
        # Exclude SQL NULL and empty string
        qs = self.get_queryset().exclude(github__isnull=True).exclude(github="")
        return Response(self.get_serializer(qs, many=True).data)

    # ------------------------------------------------------------------
    # MEDIUM
    # ------------------------------------------------------------------

    # What it does: search headline OR skills.
    # Path: GET /api/profiles/search/?q=django
    @action(detail=False, methods=["get"], url_path="search", url_name="search")
    def search(self, request):
        """Search headline / skills (case-insensitive contains)."""
        q = (request.query_params.get("q") or "").strip()
        if not q:
            return Response(
                {"detail": "Query param 'q' is required."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        # Q combines OR conditions in one filter
        qs = self.get_queryset().filter(
            Q(headline__icontains=q) | Q(skills__icontains=q)
        )
        # or (usually worse):
        # qs = (
        #     self.get_queryset().filter(headline__icontains=q)
        #     | self.get_queryset().filter(skills__icontains=q)
        # ).distinct()
        return Response(self.get_serializer(qs, many=True).data)


class InscriptionViewSet(viewsets.ModelViewSet):
    queryset = Inscription.objects.all()
    serializer_class = InscriptionSerializer

    # ------------------------------------------------------------------
    # EASY
    # ------------------------------------------------------------------

    # What it does: inscriptions still waiting for a decision.
    # Path: GET /api/inscriptions/pending/
    @action(detail=False, methods=["get"], url_path="pending", url_name="pending")
    def pending(self, request):
        """List inscriptions waiting for a decision."""
        qs = self.get_queryset().filter(situation=InscriptionStatus.PENDING)
        return Response(self.get_serializer(qs, many=True).data)

    # ------------------------------------------------------------------
    # MEDIUM
    # ------------------------------------------------------------------

    # What it does: change situation for one inscription (composite PK lookup).
    # Path: POST /api/inscriptions/set-status/
    # Body JSON: {"student": 12345, "course": 1, "situation": "accepted"}
    @action(
        detail=False,
        methods=["post"],
        url_path="set-status",
        url_name="set-status",
    )
    def set_status(self, request):
        """Update situation for one inscription (composite key lookup)."""
        student_id = request.data.get("student")
        course_id = request.data.get("course")
        situation = request.data.get("situation")
        valid = {choice.value for choice in InscriptionStatus}

        if student_id is None or course_id is None or not situation:
            return Response(
                {"detail": "Fields 'student', 'course' and 'situation' are required."},
                status=status.HTTP_400_BAD_REQUEST,
            )
        if situation not in valid:
            return Response(
                {"detail": f"Invalid situation. Choose one of: {sorted(valid)}"},
                status=status.HTTP_400_BAD_REQUEST,
            )

        try:
            # Composite PK → filter on both parts
            inscription = Inscription.objects.get(
                student_id=student_id, course_id=course_id
            )
            # or (if you already have model instances):
            # inscription = Inscription.objects.get(student=student_obj, course=course_obj)
        except Inscription.DoesNotExist:
            return Response(
                {"detail": "Inscription not found."},
                status=status.HTTP_404_NOT_FOUND,
            )

        inscription.situation = situation
        inscription.save(update_fields=["situation", "updatedAt"])
        return Response(InscriptionSerializer(inscription).data)

    # ------------------------------------------------------------------
    # ADVANCED
    # ------------------------------------------------------------------

    # What it does: accept many PENDING inscriptions in one request.
    # Path: POST /api/inscriptions/bulk-accept/
    # Body JSON: {"items": [{"student": 12345, "course": 1}, ...]}
    @action(
        detail=False,
        methods=["post"],
        url_path="bulk-accept",
        url_name="bulk-accept",
    )
    def bulk_accept(self, request):
        """Accept many pending inscriptions; return successes + per-item errors."""
        items = request.data.get("items")
        if not isinstance(items, list) or not items:
            return Response(
                {"detail": "Body must include a non-empty 'items' list."},
                status=status.HTTP_400_BAD_REQUEST,
            )

        accepted = []
        errors = []
        # Partial success: one bad item does not stop the others
        for index, item in enumerate(items):
            student_id = item.get("student")
            course_id = item.get("course")
            try:
                inscription = Inscription.objects.get(
                    student_id=student_id, course_id=course_id
                )
            except Inscription.DoesNotExist:
                errors.append({"index": index, "detail": "not found"})
                continue

            if inscription.situation != InscriptionStatus.PENDING:
                errors.append(
                    {
                        "index": index,
                        "detail": f"expected pending, got {inscription.situation}",
                    }
                )
                continue

            inscription.situation = InscriptionStatus.ACCEPTED
            inscription.save(update_fields=["situation", "updatedAt"])
            accepted.append(InscriptionSerializer(inscription).data)

        return Response(
            {
                "acceptedCount": len(accepted),
                "accepted": accepted,
                "errors": errors,
            },
            status=status.HTTP_200_OK,
        )
